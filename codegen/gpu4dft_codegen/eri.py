"""Integral math for each ERI class, emitted as backend-neutral C++.

For an integral class the emitter produces

    template <typename R>
    GPU4DFT_HD inline double eri_<name>_contracted(
        const ShellPairView& bra, int ib, const ShellPairView& ket, int ik);

which returns the contracted integral for one bra shell pair and one ket
shell pair. ``R`` is the evaluation precision; the sum over primitive pairs
is accumulated in double.

Shell-pair data conventions (see include/gpu4dft/shell_pair_view.hpp): for
each primitive pair, ``exponent`` is p = a + b, ``Px/Py/Pz`` is the Gaussian
product centre, and ``prefactor`` already folds in the contraction
coefficients, the angular normalisation, exp(-ab/p |AB|^2) and (pi/p)^{3/2}.
"""

from __future__ import annotations

import math

from .config import EriClass

_HEADER_TEMPLATE = """\
// Generated by gpu4dft_codegen. Do not edit.
#pragma once

#include "gpu4dft/boys.hpp"
#include "gpu4dft/config.hpp"
#include "gpu4dft/math.hpp"
#include "gpu4dft/shell_pair_view.hpp"

namespace gpu4dft::generated {{

{body}
}}  // namespace gpu4dft::generated
"""


def _ssss_body() -> str:
    # With the pair prefactors C_ab = c_a c_b K_AB (pi/p)^{3/2} (likewise for
    # the ket), a primitive (ss|ss) integral is
    #
    #     (ss|ss) = C_ab C_cd * 2 sqrt(rho/pi) * F_0(rho |PQ|^2),
    #     rho = p q / (p + q).
    two_over_sqrt_pi = repr(2.0 / math.sqrt(math.pi))
    return f"""\
// (ss|ss): closed form, a single Boys function F_0 per primitive quartet.
template <typename R>
GPU4DFT_HD inline double eri_ssss_contracted(const ShellPairView& bra, int ib,
                                             const ShellPairView& ket, int ik) {{
  double acc = 0.0;
  const int bra_begin = bra.prim_offset[ib];
  const int bra_end = bra.prim_offset[ib + 1];
  const int ket_begin = ket.prim_offset[ik];
  const int ket_end = ket.prim_offset[ik + 1];
  for (int ip = bra_begin; ip < bra_end; ++ip) {{
    const R p = static_cast<R>(bra.exponent[ip]);
    const R Px = static_cast<R>(bra.Px[ip]);
    const R Py = static_cast<R>(bra.Py[ip]);
    const R Pz = static_cast<R>(bra.Pz[ip]);
    const R Cab = static_cast<R>(bra.prefactor[ip]);
    for (int kp = ket_begin; kp < ket_end; ++kp) {{
      const R q = static_cast<R>(ket.exponent[kp]);
      const R PQx = Px - static_cast<R>(ket.Px[kp]);
      const R PQy = Py - static_cast<R>(ket.Py[kp]);
      const R PQz = Pz - static_cast<R>(ket.Pz[kp]);
      const R Ccd = static_cast<R>(ket.prefactor[kp]);
      const R rho = p * q / (p + q);
      const R T = rho * (PQx * PQx + PQy * PQy + PQz * PQz);
      const R value = Cab * Ccd * R({two_over_sqrt_pi}) * math::sqrt(rho) * boys_f0(T);
      acc += static_cast<double>(value);
    }}
  }}
  return acc;
}}
"""


_BODIES = {
    (0, 0, 0, 0): _ssss_body,
}


def contracted_function_name(cls: EriClass) -> str:
    return f"eri_{cls.name}_contracted"


def header_relpath(cls: EriClass) -> str:
    return f"include/gpu4dft/generated/eri_{cls.name}.hpp"


def header_include(cls: EriClass) -> str:
    return f"gpu4dft/generated/eri_{cls.name}.hpp"


def emit_class_header(cls: EriClass) -> str:
    """Return the backend-neutral header implementing ``cls``."""
    try:
        body = _BODIES[cls.angular]
    except KeyError:
        raise NotImplementedError(
            f"no integral algorithm for ({cls.name}) yet; higher angular "
            "momenta need the McMurchie-Davidson / Rys generators"
        ) from None
    return _HEADER_TEMPLATE.format(body=body())
