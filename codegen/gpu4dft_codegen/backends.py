"""Per-backend drivers: map the shared integral math onto a backend's parallelism.

Every driver exposes, for each (class, precision), a launcher with the
signature

    void eri_<class>_<backend>_<precision>(const ShellPairView& bra,
                                          const ShellPairView& ket,
                                          double* out, void* stream);

which writes the (bra pair | ket pair) block row-major into ``out``.
"""

from __future__ import annotations

from .config import PRECISIONS, CudaTuning, EriClass, Precision
from .eri import contracted_function_name, header_include

GENERATED_BANNER = "// Generated by gpu4dft_codegen. Do not edit.\n"

LAUNCHER_PARAMS = (
    "const ShellPairView& bra, const ShellPairView& ket, double* out, void* stream"
)


def launcher_name(cls: EriClass, backend: str, precision: Precision) -> str:
    return f"eri_{cls.name}_{backend}_{precision.name}"


class Backend:
    name: str
    enum: str
    extension: str

    def source_relpath(self, cls: EriClass) -> str:
        return f"src/eri_{cls.name}_{self.name}.{self.extension}"

    def emit_source(self, cls: EriClass, tuning: CudaTuning) -> str:
        raise NotImplementedError

    def _wrappers(self, cls: EriClass, driver: str) -> str:
        out = []
        for prec in PRECISIONS:
            out.append(
                f"void {launcher_name(cls, self.name, prec)}({LAUNCHER_PARAMS}) {{\n"
                f"  {driver}<{prec.ctype}>(bra, ket, out, stream);\n"
                f"}}\n"
            )
        return "\n".join(out)


class HostBackend(Backend):
    """CPU reference backend (OpenMP when available)."""

    name = "host"
    enum = "Host"
    extension = "cpp"

    def emit_source(self, cls: EriClass, tuning: CudaTuning) -> str:
        driver = f"eri_{cls.name}_host_driver"
        fn = contracted_function_name(cls)
        return f"""\
{GENERATED_BANNER}
#include "gpu4dft/generated/eri_launchers.hpp"
#include "{header_include(cls)}"

namespace gpu4dft::generated {{
namespace {{

template <typename R>
void {driver}(const ShellPairView& bra, const ShellPairView& ket, double* out,
{" " * (len(driver) + 6)}void* /*stream*/) {{
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;
#if defined(_OPENMP)
#pragma omp parallel for schedule(dynamic, 256)
#endif
  for (long long idx = 0; idx < n; ++idx) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    out[idx] = {fn}<R>(bra, ib, ket, ik);
  }}
}}

}}  // namespace

{self._wrappers(cls, driver)}
}}  // namespace gpu4dft::generated
"""


class CudaBackend(Backend):
    """CUDA backend: one thread per contracted shell quartet."""

    name = "cuda"
    enum = "Cuda"
    extension = "cu"

    def emit_source(self, cls: EriClass, tuning: CudaTuning) -> str:
        kernel = f"eri_{cls.name}_kernel"
        driver = f"eri_{cls.name}_cuda_driver"
        fn = contracted_function_name(cls)
        return f"""\
{GENERATED_BANNER}
#include <cuda_runtime.h>

#include <algorithm>

#include "gpu4dft/generated/eri_launchers.hpp"
#include "{header_include(cls)}"

namespace gpu4dft::generated {{
namespace {{

constexpr int kBlockSize = {tuning.block_size};
// Upper bound on the grid size; the grid-stride loop covers larger problems.
constexpr long long kMaxBlocks = 1LL << 20;

template <typename R>
__global__ void __launch_bounds__(kBlockSize)
    {kernel}(ShellPairView bra, ShellPairView ket, double* __restrict__ out) {{
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;
  const long long stride = static_cast<long long>(gridDim.x) * blockDim.x;
  for (long long idx = static_cast<long long>(blockIdx.x) * blockDim.x + threadIdx.x;
       idx < n; idx += stride) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    out[idx] = {fn}<R>(bra, ib, ket, ik);
  }}
}}

template <typename R>
void {driver}(const ShellPairView& bra, const ShellPairView& ket, double* out,
{" " * (len(driver) + 6)}void* stream) {{
  const long long n = static_cast<long long>(bra.npair) * ket.npair;
  if (n == 0) return;
  const long long blocks = std::min((n + kBlockSize - 1) / kBlockSize, kMaxBlocks);
  {kernel}<R><<<static_cast<unsigned>(blocks), kBlockSize, 0,
{" " * (len(kernel) + 5)}static_cast<cudaStream_t>(stream)>>>(bra, ket, out);
}}

}}  // namespace

{self._wrappers(cls, driver)}
}}  // namespace gpu4dft::generated
"""


def emit_launchers_header(classes: list[EriClass], backends: list[Backend]) -> str:
    decls = []
    for cls in classes:
        for backend in backends:
            for prec in PRECISIONS:
                decls.append(f"void {launcher_name(cls, backend.name, prec)}({LAUNCHER_PARAMS});")
    body = "\n".join(decls)
    return f"""\
{GENERATED_BANNER}#pragma once

#include "gpu4dft/shell_pair_view.hpp"

// Launchers write the (bra pair | ket pair) block row-major into
// out[bra.npair * ket.npair]. Host launchers take host pointers and ignore
// `stream`; device launchers take device pointers and enqueue the work on
// `stream` (a cudaStream_t; nullptr is the default stream).
namespace gpu4dft::generated {{

{body}

}}  // namespace gpu4dft::generated
"""


def emit_registry(classes: list[EriClass], backends: list[Backend]) -> str:
    rows = []
    for cls in classes:
        la, lb, lc, ld = cls.angular
        for backend in backends:
            for prec in PRECISIONS:
                name = launcher_name(cls, backend.name, prec)
                rows.append(
                    f"    {{{la}, {lb}, {lc}, {ld}, Backend::{backend.enum}, "
                    f"Precision::{prec.enum}, &generated::{name}, \"{name}\"}},"
                )
    table = "\n".join(rows)
    return f"""\
{GENERATED_BANNER}
#include "gpu4dft/generated/eri_launchers.hpp"
#include "gpu4dft/kernel_registry.hpp"

namespace gpu4dft {{
namespace {{

constexpr EriKernel kEriKernels[] = {{
{table}
}};

}}  // namespace

std::span<const EriKernel> eri_kernels() {{ return kEriKernels; }}

}}  // namespace gpu4dft
"""
