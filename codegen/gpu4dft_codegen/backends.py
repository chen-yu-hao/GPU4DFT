"""Per-backend drivers: map the shared integral math onto a backend's parallelism.

Every driver exposes, for each (class, precision), a launcher with the
signature

    void eri_<class>_<backend>_<precision>(const ShellPairView& bra,
                                          const ShellPairView& ket,
                                          double* out, void* stream);

which writes the (bra pair | ket pair) spherical block row-major into
``out[(ib * ket.npair + ik) * NSph + comp]``, as well as general fallback
launchers ``eri_general_<backend>_<precision>`` covering all classes up to ``g``
shells (``l <= 4``).
"""

from __future__ import annotations

from .config import PRECISIONS, CudaTuning, EriClass, Precision
from .eri import (
    GENERAL_HEADER_INCLUDE,
    cart2sph_function_name,
    eval_function_name,
    header_include,
    prim_function_name,
)

GENERATED_BANNER = "// Generated by gpu4dft_codegen. Do not edit.\n"

LAUNCHER_PARAMS = (
    "const ShellPairView& bra, const ShellPairView& ket, double* out, void* stream"
)

GENERAL_LAUNCHER_PARAMS = (
    "int la, int lb, int lc, int ld, const ShellPairView& bra, "
    "const ShellPairView& ket, double* out, void* stream"
)

GENERAL_OMEGA_LAUNCHER_PARAMS = (
    "int la, int lb, int lc, int ld, const ShellPairView& bra, "
    "const ShellPairView& ket, double omega, double* out, void* stream"
)


def launcher_name(cls: EriClass, backend: str, precision: Precision) -> str:
    return f"eri_{cls.name}_{backend}_{precision.name}"


def general_launcher_name(backend: str, precision: Precision) -> str:
    return f"eri_general_{backend}_{precision.name}"


def general_omega_launcher_name(backend: str, precision: Precision) -> str:
    return f"eri_general_{backend}_{precision.name}_omega"


class Backend:
    name: str
    enum: str
    extension: str

    def source_relpath(self, cls: EriClass) -> str:
        return f"src/eri_{cls.name}_{self.name}.{self.extension}"

    def general_source_relpath(self) -> str:
        return f"src/eri_general_{self.name}.{self.extension}"

    def emit_source(self, cls: EriClass, tuning: CudaTuning) -> str:
        raise NotImplementedError

    def emit_general_source(self) -> str:
        raise NotImplementedError

    def _wrappers(self, cls: EriClass, driver: str) -> str:
        out = []
        for prec in PRECISIONS:
            out.append(
                f"void {launcher_name(cls, self.name, prec)}({LAUNCHER_PARAMS}) {{\n"
                f"  {driver}<{prec.ctype}>(bra, ket, out, stream);\n"
                f"}}\n"
            )
        return "\n".join(out)

    def _general_wrappers(self, driver: str, omega_driver: str) -> str:
        out = []
        for prec in PRECISIONS:
            out.append(
                f"void {general_launcher_name(self.name, prec)}({GENERAL_LAUNCHER_PARAMS}) {{\n"
                f"  {driver}<{prec.ctype}>(la, lb, lc, ld, bra, ket, out, stream);\n"
                f"}}\n"
            )
            out.append(
                f"void {general_omega_launcher_name(self.name, prec)}({GENERAL_OMEGA_LAUNCHER_PARAMS}) {{\n"
                f"  {omega_driver}<{prec.ctype}>(la, lb, lc, ld, bra, ket, omega, out, stream);\n"
                f"}}\n"
            )
        return "\n".join(out)


class HostBackend(Backend):
    """CPU reference backend (OpenMP when available)."""

    name = "host"
    enum = "Host"
    extension = "cpp"

    def emit_source(self, cls: EriClass, tuning: CudaTuning) -> str:
        _ = tuning
        driver = f"eri_{cls.name}_host_driver"
        fn = eval_function_name(cls)
        nsph = cls.n_sph_components
        return f"""\
{GENERATED_BANNER}
#include "gpu4dft/generated/eri_launchers.hpp"
#include "{header_include(cls)}"

namespace gpu4dft::generated {{
namespace {{

template <typename R>
void {driver}(const ShellPairView& bra, const ShellPairView& ket, double* out,
{" " * (len(driver) + 6)}void* /*stream*/) {{
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;
#if defined(_OPENMP)
#pragma omp parallel for schedule(dynamic, 64)
#endif
  for (long long idx = 0; idx < n; ++idx) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    {fn}<R>(bra, ib, ket, ik, out + idx * {nsph}LL);
  }}
}}

}}  // namespace

{self._wrappers(cls, driver)}
}}  // namespace gpu4dft::generated
"""

    def emit_general_source(self) -> str:
        driver = "eri_general_host_driver"
        omega_driver = "eri_general_host_omega_driver"
        return f"""\
{GENERATED_BANNER}
#include "gpu4dft/generated/eri_launchers.hpp"
#include "{GENERAL_HEADER_INCLUDE}"

namespace gpu4dft::generated {{
namespace {{

template <typename R>
void {driver}(int la, int lb, int lc, int ld, const ShellPairView& bra,
              const ShellPairView& ket, double* out, void* /*stream*/) {{
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;
  const long long nsph = static_cast<long long>(n_sph(la)) * n_sph(lb) * n_sph(lc) * n_sph(ld);
#if defined(_OPENMP)
#pragma omp parallel for schedule(dynamic, 16)
#endif
  for (long long idx = 0; idx < n; ++idx) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    eri_general_eval<R>(la, lb, lc, ld, bra, ib, ket, ik, out + idx * nsph);
  }}
}}

template <typename R>
void {omega_driver}(int la, int lb, int lc, int ld, const ShellPairView& bra,
                    const ShellPairView& ket, double omega, double* out, void* /*stream*/) {{
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;
  const long long nsph = static_cast<long long>(n_sph(la)) * n_sph(lb) * n_sph(lc) * n_sph(ld);
#if defined(_OPENMP)
#pragma omp parallel for schedule(dynamic, 16)
#endif
  for (long long idx = 0; idx < n; ++idx) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    eri_general_eval<R>(la, lb, lc, ld, bra, ib, ket, ik, out + idx * nsph, omega);
  }}
}}

}}  // namespace

{self._general_wrappers(driver, omega_driver)}
}}  // namespace gpu4dft::generated
"""


def _emit_gpu_source(
    backend: Backend,
    cls: EriClass,
    tuning: CudaTuning,
    runtime_header: str,
    stream_type: str,
    shfl_expr: str,
) -> str:
    kernel = f"eri_{cls.name}_kernel"
    driver = f"eri_{cls.name}_{backend.name}_driver"
    nsph = cls.n_sph_components
    ncart = cls.n_cart_components

    if tuning.thread_mapping == "thread":
        fn = eval_function_name(cls)
        kernel_body = f"""\
template <typename R>
__global__ void __launch_bounds__(kBlockSize)
    {kernel}(ShellPairView bra, ShellPairView ket, double* __restrict__ out) {{
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;
  const long long stride = static_cast<long long>(gridDim.x) * blockDim.x;
  for (long long idx = static_cast<long long>(blockIdx.x) * blockDim.x + threadIdx.x;
       idx < n; idx += stride) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    {fn}<R>(bra, ib, ket, ik, out + idx * {nsph}LL);
  }}
}}

template <typename R>
void {driver}(const ShellPairView& bra, const ShellPairView& ket, double* out,
{" " * (len(driver) + 6)}void* stream) {{
  const long long n = static_cast<long long>(bra.npair) * ket.npair;
  if (n == 0) return;
  const long long blocks = std::min((n + kBlockSize - 1) / kBlockSize, kMaxBlocks);
  {kernel}<R><<<static_cast<unsigned>(blocks), kBlockSize, 0,
{" " * (len(kernel) + 5)}static_cast<{stream_type}>(stream)>>>(bra, ket, out);
}}"""
    else:
        prim_fn = prim_function_name(cls)
        c2s_fn = cart2sph_function_name(cls)
        kernel_body = f"""\
template <typename R>
__global__ void __launch_bounds__(kBlockSize)
    {kernel}(ShellPairView bra, ShellPairView ket, double* __restrict__ out) {{
  constexpr int kSubwarp = 32;
  const int lane = static_cast<int>(threadIdx.x) & (kSubwarp - 1);
  const long long warp_id =
      (static_cast<long long>(blockIdx.x) * blockDim.x + threadIdx.x) / kSubwarp;
  const long long total_warps =
      (static_cast<long long>(gridDim.x) * blockDim.x) / kSubwarp;
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;

  for (long long idx = warp_id; idx < n; idx += total_warps) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    const int bra_begin = bra.prim_offset[ib];
    const int n_bra_p = bra.prim_offset[ib + 1] - bra_begin;
    const int ket_begin = ket.prim_offset[ik];
    const int n_ket_p = ket.prim_offset[ik + 1] - ket_begin;
    const int n_pq = n_bra_p * n_ket_p;

    double cart[{ncart}] = {{0.0}};
    for (int pq = lane; pq < n_pq; pq += kSubwarp) {{
      const int ip = bra_begin + (pq / n_ket_p);
      const int kp = ket_begin + (pq % n_ket_p);
      {prim_fn}<R>(bra, ib, ip, ket, ik, kp, cart);
    }}
    for (int c = 0; c < {ncart}; ++c) {{
      double val = cart[c];
      for (int offset = 16; offset > 0; offset >>= 1) {{
        val += {shfl_expr};
      }}
      cart[c] = val;
    }}
    if (lane == 0) {{
      {c2s_fn}(cart, out + idx * {nsph}LL);
    }}
  }}
}}

template <typename R>
void {driver}(const ShellPairView& bra, const ShellPairView& ket, double* out,
{" " * (len(driver) + 6)}void* stream) {{
  const long long n = static_cast<long long>(bra.npair) * ket.npair;
  if (n == 0) return;
  constexpr int kWarpsPerBlock = kBlockSize / 32;
  const long long blocks = std::min((n + kWarpsPerBlock - 1) / kWarpsPerBlock, kMaxBlocks);
  {kernel}<R><<<static_cast<unsigned>(blocks), kBlockSize, 0,
{" " * (len(kernel) + 5)}static_cast<{stream_type}>(stream)>>>(bra, ket, out);
}}"""

    return f"""\
{GENERATED_BANNER}
#include <{runtime_header}>

#include <algorithm>

#include "gpu4dft/generated/eri_launchers.hpp"
#include "{header_include(cls)}"

namespace gpu4dft::generated {{
namespace {{

constexpr int kBlockSize = {tuning.block_size};
// Upper bound on the grid size; the grid-stride loop covers larger problems.
constexpr long long kMaxBlocks = 1LL << 20;

{kernel_body}

}}  // namespace

{backend._wrappers(cls, driver)}
}}  // namespace gpu4dft::generated
"""


def _emit_gpu_general_source(
    backend: Backend,
    runtime_header: str,
    stream_type: str,
) -> str:
    driver = f"eri_general_{backend.name}_driver"
    omega_driver = f"eri_general_{backend.name}_omega_driver"
    return f"""\
{GENERATED_BANNER}
#include <{runtime_header}>

#include <algorithm>

#include "gpu4dft/generated/eri_launchers.hpp"
#include "{GENERAL_HEADER_INCLUDE}"

namespace gpu4dft::generated {{
namespace {{

constexpr int kBlockSize = 64;
constexpr long long kMaxBlocks = 1LL << 18;

template <typename R>
__global__ void __launch_bounds__(kBlockSize)
    eri_general_kernel(int la, int lb, int lc, int ld, ShellPairView bra, ShellPairView ket,
                       double* __restrict__ out) {{
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;
  const long long nsph = static_cast<long long>(n_sph(la)) * n_sph(lb) * n_sph(lc) * n_sph(ld);
  const long long stride = static_cast<long long>(gridDim.x) * blockDim.x;
  for (long long idx = static_cast<long long>(blockIdx.x) * blockDim.x + threadIdx.x;
       idx < n; idx += stride) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    eri_general_eval<R>(la, lb, lc, ld, bra, ib, ket, ik, out + idx * nsph);
  }}
}}

template <typename R>
__global__ void __launch_bounds__(kBlockSize)
    eri_general_omega_kernel(int la, int lb, int lc, int ld, ShellPairView bra, ShellPairView ket,
                             double omega, double* __restrict__ out) {{
  const long long nket = ket.npair;
  const long long n = static_cast<long long>(bra.npair) * nket;
  const long long nsph = static_cast<long long>(n_sph(la)) * n_sph(lb) * n_sph(lc) * n_sph(ld);
  const long long stride = static_cast<long long>(gridDim.x) * blockDim.x;
  for (long long idx = static_cast<long long>(blockIdx.x) * blockDim.x + threadIdx.x;
       idx < n; idx += stride) {{
    const int ib = static_cast<int>(idx / nket);
    const int ik = static_cast<int>(idx - ib * nket);
    eri_general_eval<R>(la, lb, lc, ld, bra, ib, ket, ik, out + idx * nsph, omega);
  }}
}}

template <typename R>
void {driver}(int la, int lb, int lc, int ld, const ShellPairView& bra,
              const ShellPairView& ket, double* out, void* stream) {{
  const long long n = static_cast<long long>(bra.npair) * ket.npair;
  if (n == 0) return;
  const long long blocks = std::min((n + kBlockSize - 1) / kBlockSize, kMaxBlocks);
  eri_general_kernel<R><<<static_cast<unsigned>(blocks), kBlockSize, 0,
                          static_cast<{stream_type}>(stream)>>>(la, lb, lc, ld, bra, ket, out);
}}

template <typename R>
void {omega_driver}(int la, int lb, int lc, int ld, const ShellPairView& bra,
                    const ShellPairView& ket, double omega, double* out, void* stream) {{
  const long long n = static_cast<long long>(bra.npair) * ket.npair;
  if (n == 0) return;
  const long long blocks = std::min((n + kBlockSize - 1) / kBlockSize, kMaxBlocks);
  eri_general_omega_kernel<R><<<static_cast<unsigned>(blocks), kBlockSize, 0,
                                static_cast<{stream_type}>(stream)>>>(la, lb, lc, ld, bra, ket,
                                                                      omega, out);
}}

}}  // namespace

{backend._general_wrappers(driver, omega_driver)}
}}  // namespace gpu4dft::generated
"""


class CudaBackend(Backend):
    """CUDA backend: configurable thread-per-quartet or warp-cooperative shuffles."""

    name = "cuda"
    enum = "Cuda"
    extension = "cu"

    def emit_source(self, cls: EriClass, tuning: CudaTuning) -> str:
        return _emit_gpu_source(
            self,
            cls,
            tuning,
            runtime_header="cuda_runtime.h",
            stream_type="cudaStream_t",
            shfl_expr="__shfl_down_sync(0xffffffffu, val, offset)",
        )

    def emit_general_source(self) -> str:
        return _emit_gpu_general_source(
            self,
            runtime_header="cuda_runtime.h",
            stream_type="cudaStream_t",
        )


class HipBackend(Backend):
    """AMD ROCm HIP backend: wavefront-safe shuffles and <hip/hip_runtime.h>."""

    name = "hip"
    enum = "Hip"
    extension = "hip"

    def emit_source(self, cls: EriClass, tuning: CudaTuning) -> str:
        return _emit_gpu_source(
            self,
            cls,
            tuning,
            runtime_header="hip/hip_runtime.h",
            stream_type="hipStream_t",
            shfl_expr="__shfl_down(val, offset, 32)",
        )

    def emit_general_source(self) -> str:
        return _emit_gpu_general_source(
            self,
            runtime_header="hip/hip_runtime.h",
            stream_type="hipStream_t",
        )


def emit_launchers_header(classes: list[EriClass], backends: list[Backend]) -> str:
    decls = []
    for cls in classes:
        for backend in backends:
            for prec in PRECISIONS:
                decls.append(f"void {launcher_name(cls, backend.name, prec)}({LAUNCHER_PARAMS});")
    for backend in backends:
        for prec in PRECISIONS:
            decls.append(
                f"void {general_launcher_name(backend.name, prec)}({GENERAL_LAUNCHER_PARAMS});"
            )
            decls.append(
                f"void {general_omega_launcher_name(backend.name, prec)}({GENERAL_OMEGA_LAUNCHER_PARAMS});"
            )
    body = "\n".join(decls)
    return f"""\
{GENERATED_BANNER}#pragma once

#include "gpu4dft/shell_pair_view.hpp"
#include "gpu4dft/types.hpp"

// Launchers write the (bra pair | ket pair) spherical block row-major into
// out[bra.npair * ket.npair * n_sph_components]. Host launchers take host
// pointers and ignore `stream`; device launchers take device pointers and
// enqueue the work on `stream` (a cudaStream_t / hipStream_t; nullptr is the
// default stream).
namespace gpu4dft::generated {{

{body}

bool eri_general_dispatch(int la, int lb, int lc, int ld, Backend backend, Precision precision,
                          const ShellPairView& bra, const ShellPairView& ket, double* out,
                          void* stream);

bool eri_general_omega_dispatch(int la, int lb, int lc, int ld, Backend backend,
                                Precision precision, const ShellPairView& bra,
                                const ShellPairView& ket, double omega, double* out, void* stream);

}}  // namespace gpu4dft::generated
"""


def emit_registry(classes: list[EriClass], backends: list[Backend]) -> str:
    rows = []
    for cls in classes:
        la, lb, lc, ld = cls.angular
        for backend in backends:
            for prec in PRECISIONS:
                name = launcher_name(cls, backend.name, prec)
                rows.append(
                    f"    {{{la}, {lb}, {lc}, {ld}, Backend::{backend.enum}, "
                    f'Precision::{prec.enum}, &generated::{name}, "{name}"}},'
                )
    table = "\n".join(rows)

    dispatch_cases = []
    omega_dispatch_cases = []
    for backend in backends:
        for prec in PRECISIONS:
            fn = general_launcher_name(backend.name, prec)
            dispatch_cases.append(
                f"  if (backend == Backend::{backend.enum} && precision == Precision::{prec.enum}) {{\n"
                f"    {fn}(la, lb, lc, ld, bra, ket, out, stream);\n"
                f"    return true;\n"
                f"  }}"
            )
            omega_fn = general_omega_launcher_name(backend.name, prec)
            omega_dispatch_cases.append(
                f"  if (backend == Backend::{backend.enum} && precision == Precision::{prec.enum}) {{\n"
                f"    {omega_fn}(la, lb, lc, ld, bra, ket, omega, out, stream);\n"
                f"    return true;\n"
                f"  }}"
            )
    dispatch_body = "\n".join(dispatch_cases)
    omega_dispatch_body = "\n".join(omega_dispatch_cases)

    return f"""\
{GENERATED_BANNER}
#include "gpu4dft/generated/eri_launchers.hpp"
#include "gpu4dft/kernel_registry.hpp"

namespace gpu4dft {{
namespace {{

constexpr EriKernel kEriKernels[] = {{
{table}
}};

}}  // namespace

std::span<const EriKernel> eri_kernels() {{ return kEriKernels; }}

namespace generated {{

bool eri_general_dispatch(int la, int lb, int lc, int ld, Backend backend, Precision precision,
                          const ShellPairView& bra, const ShellPairView& ket, double* out,
                          void* stream) {{
{dispatch_body}
  (void)la; (void)lb; (void)lc; (void)ld; (void)bra; (void)ket; (void)out; (void)stream;
  return false;
}}

bool eri_general_omega_dispatch(int la, int lb, int lc, int ld, Backend backend,
                                Precision precision, const ShellPairView& bra,
                                const ShellPairView& ket, double omega, double* out, void* stream) {{
{omega_dispatch_body}
  (void)la; (void)lb; (void)lc; (void)ld; (void)bra; (void)ket; (void)omega; (void)out; (void)stream;
  return false;
}}

}}  // namespace generated

}}  // namespace gpu4dft
"""
