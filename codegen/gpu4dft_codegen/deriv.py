"""First-derivative (nuclear gradient) 2-electron integral code generator.

Implements ``deriv_order = 1`` via the Gaussian exponent-weighted shift
recurrence on Cartesian primitives:

    d/dA_x [x_A^lx exp(-a r_A^2)] = 2 a x_A^{lx + 1} exp(-a r_A^2)
                                    - lx x_A^{lx - 1} exp(-a r_A^2)

combined with Rys quadrature + 2D VRR + 1D HRR and translational invariance
``d/dD = -(d/dA + d/dB + d/dC)``.
"""

from __future__ import annotations

import math

from .config import MAX_SUPPORTED_L, EriClass

DERIV1_HEADER_RELPATH = "include/gpu4dft/generated/eri_deriv1.hpp"
DERIV1_HEADER_INCLUDE = "gpu4dft/generated/eri_deriv1.hpp"

TWO_OVER_SQRT_PI = repr(2.0 / math.sqrt(math.pi))


def emit_deriv1_header() -> str:
    """Emit backend-neutral ``GPU4DFT_HD`` 1st-derivative ERI kernel header."""
    return f"""\
// Generated by gpu4dft_codegen (deriv_order=1). Do not edit.
#pragma once

#include "gpu4dft/boys.hpp"
#include "gpu4dft/config.hpp"
#include "gpu4dft/harmonics.hpp"
#include "gpu4dft/math.hpp"
#include "gpu4dft/rys.hpp"
#include "gpu4dft/shell_pair_view.hpp"

namespace gpu4dft::generated {{

namespace detail_deriv1 {{

// Builds 1D Rys VRR + HRR table I[0..la+1][0..lb+1][0..lc+1][0..ld] (with +1
// angular-momentum headroom on A, B, and C; D uses translational invariance).
template <typename R>
GPU4DFT_HD inline void rys_1d_deriv1(int la, int lb, int lc, int ld, R C00, R D00, R B10, R B01,
                                     R B00, R AB, R CD, R I[6][6][6][5]) {{
  const int la_hi = la + 1;
  const int lb_hi = lb + 1;
  const int lc_hi = lc + 1;
  const int lab = la + lb + 1;
  const int lcd = lc + ld + 1;

  R G[10][10];
  G[0][0] = R(1);
  for (int n = 0; n < lab; ++n) {{
    G[n + 1][0] = C00 * G[n][0] + (n > 0 ? R(n) * B10 * G[n - 1][0] : R(0));
  }}
  for (int m = 0; m < lcd; ++m) {{
    for (int n = 0; n <= lab; ++n) {{
      R val = D00 * G[n][m];
      if (m > 0) val += R(m) * B01 * G[n][m - 1];
      if (n > 0) val += R(n) * B00 * G[n - 1][m];
      G[n][m + 1] = val;
    }}
  }}

  R H[6][6][10];
  R cur[10][10];
  for (int n = 0; n <= lab; ++n)
    for (int m = 0; m <= lcd; ++m) cur[n][m] = G[n][m];
  for (int j = 0; j <= lb_hi; ++j) {{
    const int i_max = (la_hi < lab - j) ? la_hi : (lab - j);
    for (int i = 0; i <= i_max; ++i)
      for (int m = 0; m <= lcd; ++m) H[i][j][m] = cur[i][m];
    if (j < lb_hi) {{
      for (int i = 0; i <= lab - j - 1; ++i)
        for (int m = 0; m <= lcd; ++m) cur[i][m] = cur[i + 1][m] + AB * cur[i][m];
    }}
  }}

  for (int j = 0; j <= lb_hi; ++j) {{
    const int i_max = (la_hi < lab - j) ? la_hi : (lab - j);
    for (int i = 0; i <= i_max; ++i) {{
      R kcur[10];
      for (int m = 0; m <= lcd; ++m) kcur[m] = H[i][j][m];
      for (int l = 0; l <= ld; ++l) {{
        const int k_max = (lc_hi < lcd - l) ? lc_hi : (lcd - l);
        for (int k = 0; k <= k_max; ++k) I[i][j][k][l] = kcur[k];
        if (l < ld) {{
          for (int k = 0; k <= lcd - l - 1; ++k) kcur[k] = kcur[k + 1] + CD * kcur[k];
        }}
      }}
    }}
  }}
}}

}}  // namespace detail_deriv1

// Generic functor-driven 1st nuclear derivative contraction of quartet (la,lb|lc,ld)
// into `grad12[0..11]` = (d/dA_xyz, d/dB_xyz, d/dC_xyz, d/dD_xyz).
template <typename R, typename GammaFn>
GPU4DFT_HD inline void eri_quartet_grad_contract_fn(
    int la, int lb, int lc, int ld, const ShellPairView& bra, int ib, const ShellPairView& ket,
    int ik, GammaFn gamma_fn, double grad12[12]) {{
  for (int i = 0; i < 12; ++i) grad12[i] = 0.0;

  const int nca = n_cart(la), ncb = n_cart(lb), ncc = n_cart(lc), ncd = n_cart(ld);
  const int n_roots = (la + lb + lc + ld + 1) / 2 + 1;

  const double Ax = bra.Ax[ib], Ay = bra.Ay[ib], Az = bra.Az[ib];
  const double Bx = bra.Bx[ib], By = bra.By[ib], Bz = bra.Bz[ib];
  const double Cx = ket.Ax[ik], Cy = ket.Ay[ik], Cz = ket.Az[ik];
  const double Dx = ket.Bx[ik], Dy = ket.By[ik], Dz = ket.Bz[ik];
  const R ABx = static_cast<R>(Ax - Bx), ABy = static_cast<R>(Ay - By), ABz = static_cast<R>(Az - Bz);
  const R CDx = static_cast<R>(Cx - Dx), CDy = static_cast<R>(Cy - Dy), CDz = static_cast<R>(Cz - Dz);

  CartTriple ta[15], tb[15], tc[15], td[15];
  for (int ia = 0; ia < nca; ++ia) ta[ia] = cart_triple(la, ia);
  for (int ib_c = 0; ib_c < ncb; ++ib_c) tb[ib_c] = cart_triple(lb, ib_c);
  for (int ic = 0; ic < ncc; ++ic) tc[ic] = cart_triple(lc, ic);
  for (int id = 0; id < ncd; ++id) td[id] = cart_triple(ld, id);

  double gAx = 0.0, gAy = 0.0, gAz = 0.0;
  double gBx = 0.0, gBy = 0.0, gBz = 0.0;
  double gCx = 0.0, gCy = 0.0, gCz = 0.0;

  const int bra_begin = bra.prim_offset[ib];
  const int bra_end = bra.prim_offset[ib + 1];
  const int ket_begin = ket.prim_offset[ik];
  const int ket_end = ket.prim_offset[ik + 1];

  for (int ip = bra_begin; ip < bra_end; ++ip) {{
    const R p = static_cast<R>(bra.exponent[ip]);
    const R two_a = R(2) * static_cast<R>(bra.alpha_a[ip]);
    const R two_b = R(2) * static_cast<R>(bra.alpha_b[ip]);
    const R Px = static_cast<R>(bra.Px[ip]);
    const R Py = static_cast<R>(bra.Py[ip]);
    const R Pz = static_cast<R>(bra.Pz[ip]);
    const R Cab = static_cast<R>(bra.prefactor[ip]);
    const R PAx = Px - static_cast<R>(Ax);
    const R PAy = Py - static_cast<R>(Ay);
    const R PAz = Pz - static_cast<R>(Az);
    const R inv_2p = R(0.5) / p;

    for (int kp = ket_begin; kp < ket_end; ++kp) {{
      const R q = static_cast<R>(ket.exponent[kp]);
      const R two_c = R(2) * static_cast<R>(ket.alpha_a[kp]);
      const R Qx = static_cast<R>(ket.Px[kp]);
      const R Qy = static_cast<R>(ket.Py[kp]);
      const R Qz = static_cast<R>(ket.Pz[kp]);
      const R Ccd = static_cast<R>(ket.prefactor[kp]);
      const R PQx = Px - Qx, PQy = Py - Qy, PQz = Pz - Qz;
      const R pq_sum = p + q;
      const R rho = p * q / pq_sum;
      const R T = rho * (PQx * PQx + PQy * PQy + PQz * PQz);
      const R scale = Cab * Ccd * R({TWO_OVER_SQRT_PI}) * math::sqrt(rho);

      R u_roots[10];
      R w_weights[10];
      rys_roots_weights<R>(n_roots, T, u_roots, w_weights);

      const R inv_2q = R(0.5) / q;
      const R inv_2pq = R(0.5) / pq_sum;
      const R rho_over_p = rho / p;
      const R rho_over_q = rho / q;
      const R QCx = Qx - static_cast<R>(Cx);
      const R QCy = Qy - static_cast<R>(Cy);
      const R QCz = Qz - static_cast<R>(Cz);

      for (int r = 0; r < n_roots; ++r) {{
        const R u = u_roots[r];
        const double Wr = static_cast<double>(scale * w_weights[r]);
        const R B00 = inv_2pq * u;
        const R B10 = inv_2p * (R(1) - rho_over_p * u);
        const R B01 = inv_2q * (R(1) - rho_over_q * u);

        R Ix[6][6][6][5];
        R Iy[6][6][6][5];
        R Iz[6][6][6][5];
        detail_deriv1::rys_1d_deriv1<R>(la, lb, lc, ld, PAx - rho_over_p * u * PQx,
                                        QCx + rho_over_q * u * PQx, B10, B01, B00, ABx, CDx, Ix);
        detail_deriv1::rys_1d_deriv1<R>(la, lb, lc, ld, PAy - rho_over_p * u * PQy,
                                        QCy + rho_over_q * u * PQy, B10, B01, B00, ABy, CDy, Iy);
        detail_deriv1::rys_1d_deriv1<R>(la, lb, lc, ld, PAz - rho_over_p * u * PQz,
                                        QCz + rho_over_q * u * PQz, B10, B01, B00, ABz, CDz, Iz);

        for (int ia = 0; ia < nca; ++ia) {{
          const int ax = ta[ia].lx, ay = ta[ia].ly, az = ta[ia].lz;
          for (int ib_c = 0; ib_c < ncb; ++ib_c) {{
            const int bx = tb[ib_c].lx, by = tb[ib_c].ly, bz = tb[ib_c].lz;
            for (int ic = 0; ic < ncc; ++ic) {{
              const int cx = tc[ic].lx, cy = tc[ic].ly, cz = tc[ic].lz;
              for (int id = 0; id < ncd; ++id) {{
                const double w_gam = Wr * gamma_fn(ia, ib_c, ic, id);
                if (w_gam == 0.0) continue;
                const int dx = td[id].lx, dy = td[id].ly, dz = td[id].lz;

                const R ix0 = Ix[ax][bx][cx][dx];
                const R iy0 = Iy[ay][by][cy][dy];
                const R iz0 = Iz[az][bz][cz][dz];

                const R dAx = two_a * Ix[ax + 1][bx][cx][dx] -
                              (ax > 0 ? R(ax) * Ix[ax - 1][bx][cx][dx] : R(0));
                const R dAy = two_a * Iy[ay + 1][by][cy][dy] -
                              (ay > 0 ? R(ay) * Iy[ay - 1][by][cy][dy] : R(0));
                const R dAz = two_a * Iz[az + 1][bz][cz][dz] -
                              (az > 0 ? R(az) * Iz[az - 1][bz][cz][dz] : R(0));

                const R dBx = two_b * Ix[ax][bx + 1][cx][dx] -
                              (bx > 0 ? R(bx) * Ix[ax][bx - 1][cx][dx] : R(0));
                const R dBy = two_b * Iy[ay][by + 1][cy][dy] -
                              (by > 0 ? R(by) * Iy[ay][by - 1][cy][dy] : R(0));
                const R dBz = two_b * Iz[az][bz + 1][cz][dz] -
                              (bz > 0 ? R(bz) * Iz[az][bz - 1][cz][dz] : R(0));

                const R dCx = two_c * Ix[ax][bx][cx + 1][dx] -
                              (cx > 0 ? R(cx) * Ix[ax][bx][cx - 1][dx] : R(0));
                const R dCy = two_c * Iy[ay][by][cy + 1][dy] -
                              (cy > 0 ? R(cy) * Iy[ay][by][cy - 1][dy] : R(0));
                const R dCz = two_c * Iz[az][bz][cz + 1][dz] -
                              (cz > 0 ? R(cz) * Iz[az][bz][cz - 1][dz] : R(0));

                gAx += w_gam * static_cast<double>(dAx * iy0 * iz0);
                gAy += w_gam * static_cast<double>(ix0 * dAy * iz0);
                gAz += w_gam * static_cast<double>(ix0 * iy0 * dAz);

                gBx += w_gam * static_cast<double>(dBx * iy0 * iz0);
                gBy += w_gam * static_cast<double>(ix0 * dBy * iz0);
                gBz += w_gam * static_cast<double>(ix0 * iy0 * dBz);

                gCx += w_gam * static_cast<double>(dCx * iy0 * iz0);
                gCy += w_gam * static_cast<double>(ix0 * dCy * iz0);
                gCz += w_gam * static_cast<double>(ix0 * iy0 * dCz);
              }}
            }}
          }}
        }}
      }}
    }}
  }}

  grad12[0] = gAx;
  grad12[1] = gAy;
  grad12[2] = gAz;
  grad12[3] = gBx;
  grad12[4] = gBy;
  grad12[5] = gBz;
  grad12[6] = gCx;
  grad12[7] = gCy;
  grad12[8] = gCz;
  grad12[9] = -(gAx + gBx + gCx);
  grad12[10] = -(gAy + gBy + gCy);
  grad12[11] = -(gAz + gBz + gCz);
}}

// On-the-fly contraction with Cartesian density matrix D_cart [ncart_tot x ncart_tot]
// (zero 4-index stack workspace even for f/g shells!).
template <typename R>
GPU4DFT_HD inline void eri_quartet_grad_direct_dm(
    int la, int lb, int lc, int ld, const ShellPairView& bra, int ib, const ShellPairView& ket,
    int ik, const double* D_cart, int ncart_tot, int off_a, int off_b, int off_c, int off_d,
    double w_sym, double k_fraction, double grad12[12]) {{
  const int ncb = n_cart(lb), ncc = n_cart(lc), ncd = n_cart(ld);
  (void)ncb;
  (void)ncc;
  (void)ncd;
  const double half_w = 0.5 * w_sym;
  const double q_kfrac = 0.25 * k_fraction;
  auto gamma_fn = [=](int ia, int ib_c, int ic, int id) -> double {{
    const int a = off_a + ia;
    const int b = off_b + ib_c;
    const int c = off_c + ic;
    const int d = off_d + id;
    const double dab = D_cart[a * ncart_tot + b];
    const double dcd = D_cart[c * ncart_tot + d];
    const double dac = D_cart[a * ncart_tot + c];
    const double dbd = D_cart[b * ncart_tot + d];
    const double dad = D_cart[a * ncart_tot + d];
    const double dbc = D_cart[b * ncart_tot + c];
    return half_w * (dab * dcd - q_kfrac * (dac * dbd + dad * dbc));
  }};
  eri_quartet_grad_contract_fn<R>(la, lb, lc, ld, bra, ib, ket, ik, gamma_fn, grad12);
}}

}}  // namespace gpu4dft::generated
"""


def validate_deriv_class(cls: EriClass) -> None:
    for l in cls.angular:
        if l < 0 or l > MAX_SUPPORTED_L:
            raise NotImplementedError(
                f"derivative integral class ({cls.name}) exceeds max_l={MAX_SUPPORTED_L}"
            )
