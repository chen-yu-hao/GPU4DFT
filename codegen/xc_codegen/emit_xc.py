"""Emit backend-neutral Host/CUDA/HIP C++20 header ``xc_kernels.hpp``."""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

from .functionals import (
    NAMED_FUNCTIONALS,
    BaseFunctionalSpec,
    build_base_functionals,
    differentiate_functional,
)
from .sym_diff import Binary, Const, Expr, Unary, Var, Where, cse

XC_KERNELS_RELPATH = "include/gpu4dft/generated/xc_kernels.hpp"


def _fmt_const(val: float) -> str:
    s = repr(float(val))
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s


def _emit_expr(node: Expr, sym_names: Mapping[Expr, str]) -> str:
    if node in sym_names:
        return sym_names[node]

    def _sub(child: Expr) -> str:
        if child in sym_names:
            return sym_names[child]
        if isinstance(child, (Const, Var)):
            return _emit_expr(child, sym_names)
        return f"({_emit_expr(child, sym_names)})"

    if isinstance(node, Const):
        return _fmt_const(node.value)
    if isinstance(node, Var):
        return node.name
    if isinstance(node, Unary):
        arg = _emit_expr(node.arg, sym_names)
        if node.op == "neg":
            return f"(-{_sub(node.arg)})"
        if node.op in ("sqrt", "cbrt", "log", "log1p", "exp", "expm1", "atan", "asinh"):
            return f"::{node.op}({arg})"
        raise ValueError(f"unsupported unary op {node.op!r}")
    if isinstance(node, Binary):
        lhs = _sub(node.lhs)
        rhs = _sub(node.rhs)
        if node.op == "add":
            return f"{lhs} + {rhs}"
        if node.op == "sub":
            return f"{lhs} - {rhs}"
        if node.op == "mul":
            return f"{lhs} * {rhs}"
        if node.op == "div":
            return f"{lhs} / {rhs}"
        if node.op == "pow":
            raw_l = _emit_expr(node.lhs, sym_names)
            if isinstance(node.rhs, Const):
                k = node.rhs.value
                if k == 2.0:
                    return f"xc_sq({raw_l})"
                if k == 3.0:
                    return f"xc_cube({raw_l})"
                if k == 4.0:
                    return f"xc_sq(xc_sq({raw_l}))"
                if k == -2.0:
                    return f"(1.0 / xc_sq({raw_l}))"
                if k == -3.0:
                    return f"(1.0 / xc_cube({raw_l}))"
            raw_r = _emit_expr(node.rhs, sym_names)
            return f"::pow({raw_l}, {raw_r})"
        raise ValueError(f"unsupported binary op {node.op!r}")
    if isinstance(node, Where):
        op_map = {"lt": "<", "le": "<=", "gt": ">", "ge": ">="}
        cl = _sub(node.cond_lhs)
        cr = _sub(node.cond_rhs)
        tv = _sub(node.true_val)
        fv = _sub(node.false_val)
        return f"(({cl} {op_map[node.cond_op]} {cr}) ? {tv} : {fv})"
    raise TypeError(f"unknown Expr node {type(node)!r}")


def _emit_component_fn(spec: BaseFunctionalSpec, derivs: dict[str, Expr], order: int) -> str:
    if order == 1:
        keys = ("zk", "vrho", "vsigma", "vtau")
        fn_name = f"eval_{spec.name}_d1"
    else:
        keys = (
            "zk",
            "vrho",
            "vsigma",
            "vtau",
            "v2rho2",
            "v2rhosigma",
            "v2sigma2",
            "v2rhotau",
            "v2sigmatau",
            "v2tau2",
        )
        fn_name = f"eval_{spec.name}_d2"

    outputs = [derivs[k] for k in keys]
    bindings, roots = cse(outputs)

    lines: list[str] = []
    lines.append(
        f"GPU4DFT_HD inline void {fn_name}(double rho, double sigma, double tau, double scale, XcPointOut& out) {{"
    )
    lines.append("  (void)rho; (void)sigma; (void)tau;")

    sym_names: dict[Expr, str] = {}
    for var_name, node in bindings:
        expr_code = _emit_expr(node, sym_names)
        lines.append(f"  const double {var_name} = {expr_code};")
        sym_names[node] = var_name

    for key, root in zip(keys, roots):
        if isinstance(root, Const) and root.value == 0.0:
            continue
        expr_code = _emit_expr(root, sym_names)
        lines.append(f"  out.{key} += scale * ({expr_code});")

    lines.append("}")
    return "\n".join(lines)


def _enum_ident(name: str) -> str:
    return "k_" + name.replace(",", "_").replace("-", "_")


def emit_xc_kernels_header() -> str:
    base_specs = build_base_functionals()
    base_derivs = {s.name: differentiate_functional(s) for s in base_specs}

    out: list[str] = []
    out.append("// Auto-generated by codegen/xc_codegen — DO NOT EDIT MANUALLY.")
    out.append("#pragma once")
    out.append("")
    out.append("#include <math.h>")
    out.append("#include <cctype>")
    out.append("#include <stdexcept>")
    out.append("#include <string>")
    out.append("#include <string_view>")
    out.append("")
    out.append('#include "gpu4dft/config.hpp"')
    out.append("")
    out.append("namespace gpu4dft::xc_gen {")
    out.append("")
    out.append("enum class XcFamily : int {")
    out.append("  LDA = 0,")
    out.append("  GGA = 1,")
    out.append("  MGGA = 2,")
    out.append("};")
    out.append("")
    out.append("enum class XcFunctionalId : int {")
    for idx, nf in enumerate(NAMED_FUNCTIONALS):
        out.append(f"  {_enum_ident(nf.name)} = {idx},")
    out.append("};")
    out.append("")
    out.append("struct XcPointOut {")
    out.append("  double zk = 0.0;")
    out.append("  double vrho = 0.0;")
    out.append("  double vsigma = 0.0;")
    out.append("  double vtau = 0.0;")
    out.append("  double v2rho2 = 0.0;")
    out.append("  double v2rhosigma = 0.0;")
    out.append("  double v2sigma2 = 0.0;")
    out.append("  double v2rhotau = 0.0;")
    out.append("  double v2sigmatau = 0.0;")
    out.append("  double v2tau2 = 0.0;")
    out.append("};")
    out.append("")
    out.append("GPU4DFT_HD constexpr double xc_sq(double x) { return x * x; }")
    out.append("GPU4DFT_HD constexpr double xc_cube(double x) { return x * x * x; }")
    out.append("")

    for spec in base_specs:
        out.append(_emit_component_fn(spec, base_derivs[spec.name], order=1))
        out.append("")
        out.append(_emit_component_fn(spec, base_derivs[spec.name], order=2))
        out.append("")

    # Emit unified device/host dispatcher
    out.append(
        "GPU4DFT_HD inline void eval_xc_point("
        "XcFunctionalId id, double rho, double sigma, double tau, int deriv, "
        "XcPointOut& out, double rho_cutoff = 1e-15) {"
    )
    out.append("  out = XcPointOut{};")
    out.append("  if (!(rho >= rho_cutoff)) return;")
    out.append("  if (sigma < 0.0) sigma = 0.0;")
    out.append("  const bool need_d2 = (deriv >= 2);")
    out.append("  switch (id) {")
    for nf in NAMED_FUNCTIONALS:
        out.append(f"    case XcFunctionalId::{_enum_ident(nf.name)}:")
        if not nf.components:
            out.append("      break;")
            continue
        out.append("      if (!need_d2) {")
        for comp_name, weight in nf.components:
            out.append(
                f"        eval_{comp_name}_d1(rho, sigma, tau, {_fmt_const(weight)}, out);"
            )
        out.append("      } else {")
        for comp_name, weight in nf.components:
            out.append(
                f"        eval_{comp_name}_d2(rho, sigma, tau, {_fmt_const(weight)}, out);"
            )
        out.append("      }")
        out.append("      break;")
    out.append("  }")
    out.append("}")
    out.append("")

    # Host string normalization and lookup helpers
    out.append("inline std::string normalize_xc_name(std::string_view raw) {")
    out.append("  std::string s;")
    out.append("  s.reserve(raw.size());")
    out.append("  for (char ch : raw) {")
    out.append("    if (ch == ' ' || ch == '\\t' || ch == '\\n' || ch == '\\r') continue;")
    out.append("    if (ch == '-') { s.push_back('_'); continue; }")
    out.append(
        "    s.push_back(static_cast<char>(std::tolower(static_cast<unsigned char>(ch))));"
    )
    out.append("  }")
    out.append("  return s;")
    out.append("}")
    out.append("")

    out.append("inline XcFunctionalId parse_xc_functional(std::string_view xc_name) {")
    out.append("  const std::string key = normalize_xc_name(xc_name);")
    for nf in NAMED_FUNCTIONALS:
        all_names = (nf.name, *nf.aliases)
        conds = " || ".join(f'key == "{n.lower().replace("-", "_")}"' for n in all_names)
        out.append(f"  if ({conds}) return XcFunctionalId::{_enum_ident(nf.name)};")
    out.append(
        '  throw std::invalid_argument("Unsupported XC functional: " + std::string(xc_name));'
    )
    out.append("}")
    out.append("")

    out.append("GPU4DFT_HD constexpr XcFamily xc_functional_family(XcFunctionalId id) {")
    out.append("  switch (id) {")
    for nf in NAMED_FUNCTIONALS:
        out.append(
            f"    case XcFunctionalId::{_enum_ident(nf.name)}: return XcFamily::{nf.family};"
        )
    out.append("  }")
    out.append("  return XcFamily::LDA;")
    out.append("}")
    out.append("")

    out.append(
        "GPU4DFT_HD constexpr double xc_exact_exchange_fraction_by_id(XcFunctionalId id) {"
    )
    out.append("  switch (id) {")
    for nf in NAMED_FUNCTIONALS:
        out.append(
            f"    case XcFunctionalId::{_enum_ident(nf.name)}: return {_fmt_const(nf.hyb_exx)};"
        )
    out.append("  }")
    out.append("  return 0.0;")
    out.append("}")
    out.append("")
    out.append("}  // namespace gpu4dft::xc_gen")
    out.append("")
    return "\n".join(out)


def generate() -> dict[str, str]:
    return {XC_KERNELS_RELPATH: emit_xc_kernels_header()}


def write_outputs(out_dir: Path, files: Mapping[str, str]) -> None:
    for relpath, text in files.items():
        path = out_dir / relpath
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
